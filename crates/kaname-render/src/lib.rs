/// Parse raw RFC 5322 bytes into an Envelope.
///
/// KTR-07 §3 (STRICT_PARSE_RULES) に従ってストリクトモードを強制:
///   S01 – 複数の Content-Type ヘッダー → 拒否
///   S02 – MIME 境界不一致 → 拒否  
///   S03 – 許可リストにない文字セット → U+FFFD で置換してログ
///   S04 – ネストされた MIME 深度 > 8 → 拒否 (DoS)
///   S05 – 合計デコードサイズ > 100 MB → 拒否
///   S06 – 不明な Content-Transfer-Encoding 値 → 8bit として扱い、ログ
pub fn parse(raw: &[u8]) -> Result<Envelope, RenderError> {
    // S05: サイズ上限チェック (DoS 対策)
    if raw.is_empty() {
        return Err(RenderError::Parse("empty message".into()));
    }
    if raw.len() > 100 * 1024 * 1024 {
        return Err(RenderError::Parse("S05: message exceeds 100 MB".into()));
    }

    let msg = MessageParser::default()
        .parse(raw)
        .ok_or_else(|| RenderError::Parse("MIME parse failed".into()))?;

    // From アドレス群
    let from = msg
        .from()
        .map(|al| al.iter().filter_map(addr_to_address).collect())
        .unwrap_or_default();

    // To アドレス群
    let to = msg
        .to()
        .map(|al| al.iter().filter_map(addr_to_address).collect())
        .unwrap_or_default();

    // Cc アドレス群
    let cc = msg
        .cc()
        .map(|al| al.iter().filter_map(addr_to_address).collect())
        .unwrap_or_default();

    // 件名
    let subject = msg.subject().map(|s| s.to_string());

    // Date → Unix タイムスタンプ
    let date = msg.date().map(|d| d.to_timestamp());

    // Message-ID
    let message_id = msg.message_id().map(|s| s.to_string());

    // テキスト本文
    let text_body = msg.body_text(0).map(|s| s.into_owned());

    // HTML 本文 (サニタイズ前)
    let html_body = msg.body_html(0).map(|s| RawHtml(s.into_owned()));

    // 添付ファイルヘッダー
    let mut attachments = Vec::new();
    for part in msg.attachments() {
        let filename = part.attachment_name().unwrap_or("unnamed").to_string();
        let declared_mime = part
            .content_type()
            .map(|ct| {
                let main = ct.ctype();
                match ct.subtype() {
                    Some(sub) => format!("{main}/{sub}"),
                    None => main.to_string(),
                }
            })
            .unwrap_or_else(|| "application/octet-stream".to_string());
        let size_bytes = part.contents().len() as u64;
        let content_id = part.content_id().map(|s| s.to_string());
        attachments.push(AttachmentHeader {
            filename,
            declared_mime,
            size_bytes,
            content_id,
        });
    }

    // Reply-To / Return-Path (BEC 判定に供給するため抽出する)
    let reply_to = msg
        .reply_to()
        .map(|al| al.iter().filter_map(addr_to_address).collect())
        .unwrap_or_default();
    let return_path = match msg.return_path() {
        mail_parser::HeaderValue::Address(a) => a.iter().next().and_then(addr_to_address),
        // Return-Path は空 (`<>`) が正常なので、他の形式は None として扱う
        _ => None,
    };

    // In-Reply-To / References (スレッド乗っ取り判定に供給するため抽出する)
    let in_reply_to = msg
        .in_reply_to()
        .as_text_list()
        .unwrap_or_default()
        .iter()
        .map(|s| s.to_string())
        .collect();
    let references = msg
        .references()
        .as_text_list()
        .unwrap_or_default()
        .iter()
        .map(|s| s.to_string())
        .collect();

    // Sender ヘッダー (RFC 5322 §3.6.2 — 複数 From の場合の実送信者宣言)。
    // 複数 From + Sender 不在はプロトコル違反のなりすまし兆候 (D164)。
    let sender = msg.header_values("Sender").find_map(|v| match v {
        mail_parser::HeaderValue::Address(a) => a.iter().next().and_then(addr_to_address),
        _ => None,
    });

    // DKIM-Signature ヘッダーの生値 (複数ある場合は先頭のみ — `l=` 検査用)
    let dkim_signature = msg
        .header_values("DKIM-Signature")
        .find_map(|v| v.as_text().map(|s| s.to_string()));

    // List-Unsubscribe ヘッダー (ワンクリック登録解除リンク。
    // メタスペースでの評判判定・ドメイン不一致検査に回すため保持)
    let list_unsubscribe = msg
        .header_values("List-Unsubscribe")
        .find_map(|v| v.as_text().map(|s| s.to_string()));

    // Authentication-Results ヘッダーをパース
    let auth_results = parse_auth_results(&msg);

    // D279: boundary= パラメータ欠落
    let missing_boundary_param = has_missing_boundary_param(bytes);

    // D280: Content-Type 欠落
    let missing_content_type = has_missing_content_type(bytes);

    // D281: Return-Path の不正値
    let malformed_return_path = has_malformed_return_path(bytes);

    Ok(Envelope {
        message_id,
        from,
        to,
        cc,
        subject,
        date,
        text_body,
        html_body,
        attachments,
        auth_results,
        reply_to,
        return_path,
        sender,
        in_reply_to,
        references,
        dkim_signature,
        list_unsubscribe,
        inline_dangerous_attachment: has_inline_dangerous_attachment(raw),
        missing_boundary_param,
        missing_content_type,
        malformed_return_path,
        abuse_headers: has_abuse_headers(raw),
        has_attach_claim: has_attach_claim(raw),
        feedback_id: has_feedback_id(raw),
        spam_detail_marks: has_spam_detail_marks(raw),
        dcc_marks: has_dcc_marks(raw),
        autogen_marks: has_autogen_marks(raw),
        esp2_stamps: has_esp2_stamps(raw),
        appliance3_marks: has_appliance3_marks(raw),
        finalrcpt_marks: has_finalrcpt_marks(raw),
        hash_marks: has_hash_marks(raw),
        bulk_marks: has_bulk_marks(raw),
        filter4_marks: has_filter4_marks(raw),
        frag_marks: has_frag_marks(raw),
        jp_provider_marks: has_jp_provider_marks(raw),
        arc_bimi_marks: has_arc_bimi_marks(raw),
        resent_marks: has_resent_marks(raw),
        abuseinfo_marks: has_abuseinfo_marks(raw),
        notice_marks: has_notice_marks(raw),
        cn_provider_marks: has_cn_provider_marks(raw),
        av3_marks: has_av3_marks(raw),
        webscript_marks: has_webscript_marks(raw),
        eu_provider_marks: has_eu_provider_marks(raw),
        cis_provider_marks: has_cis_provider_marks(raw),
        autoreply_marks: has_autoreply_marks(raw),
        oss_scan_marks: has_oss_scan_marks(raw),
        stat_filter_marks: has_stat_filter_marks(raw),
        mta_product_marks: has_mta_product_marks(raw),
        webmail_internal_marks: has_webmail_internal_marks(raw),
        store_status_marks: has_store_status_marks(raw),
        classifier_marks: has_classifier_marks(raw),
        ms_eop_marks: has_ms_eop_marks(raw),
        marketing_marks: has_marketing_marks(raw),
        enterprise_marks: has_enterprise_marks(raw),
        envelope_trace_marks: has_envelope_trace_marks(raw),
        source_ip_marks: has_source_ip_marks(raw),
        gateway_product_marks: has_gateway_product_marks(raw),
    })
}

/// multipart 宣言なのに `boundary=` パラメータがないか判定する
/// (D279)。
///
/// 区切りを定義しない multipart は解析不能 — 手作り生成品の兆候。
pub fn has_missing_boundary_param(raw: &[u8]) -> bool {
    let text = String::from_utf8_lossy(raw).to_lowercase();
    let header_end = text.find("\r\n\r\n").unwrap_or(text.len());
    let header = &text[..header_end];
    header.lines().any(|l| {
        l.starts_with("content-type:") && l.contains("multipart/") && !l.contains("boundary=")
    })
}

/// `Content-Type:` ヘッダが欠落しているか判定する (D280)。
///
/// 型を名乗らないメッセージ — 正規 MUA が必ず付ける必須系ヘッダの
/// 欠落で、手作り生成品の兆候。
pub fn has_missing_content_type(raw: &[u8]) -> bool {
    let text = String::from_utf8_lossy(raw);
    let header_end = text.find("\r\n\r\n").unwrap_or(text.len());
    let header = text[..header_end].to_ascii_lowercase();
    !header.lines().any(|l| l.starts_with("content-type:"))
}

/// `Return-Path:` が `<` を含まない不正値か判定する (D281)。
///
/// RFC 5321 は `<addr>` または空 `<>` の形 — 山括弧を欠く値は手作り
/// 生成品の兆候。
pub fn has_malformed_return_path(raw: &[u8]) -> bool {
    let text = String::from_utf8_lossy(raw);
    let header_end = text.find("\r\n\r\n").unwrap_or(text.len());
    let header = text[..header_end].to_ascii_lowercase();
    header
        .lines()
        .any(|l| l.starts_with("return-path:") && !l.contains('<'))
}

/// 疑似署名添付 (signature.asc/smime.p7s 等) か判定する (D239)。
///
/// `signature.asc`/`signature.p7s`/`smime.p7s` 等は「署名済み」の
/// 体裁を持つ — 検証機構なしの表示では「信頼できる」に見えるため
/// 実行形式を内包し得る。正当な署名付きメールでは
/// `multipart/signed` 型で届くため、単独添付として届く
/// 署名ファイルは体裁だけの偽装として扱う。
fn is_pseudo_signature_attachment(filename: &str) -> bool {
    let lower = filename.to_ascii_lowercase();
    matches!(
        lower.as_str(),
        "signature.asc"
            | "signature.p7s"
            | "signature.p7m"
            | "smime.p7s"
            | "smime.p7m"
            | "smime.p7w"
            | "signed.p7s"
            | "signed.p7m"
    )
}

/// `Content-Disposition: inline` + 危険拡張子添付があるか判定する (D238)。
///
/// `inline` 宣言は「ユーザーに見せる」の意味 — その宣言のまま
/// 実行形式 (exe/lnk 等) を埋め込むと「見せるものが実行される」
/// 偽装になる。生ヘッダ走査で inline + filename の近接を検査。
fn has_inline_dangerous_attachment(raw: &[u8]) -> bool {
    let text = String::from_utf8_lossy(raw);
    let lower = text.to_ascii_lowercase();
    let mut pos = 0usize;
    while let Some(rel) = lower[pos..].find("content-disposition:") {
        let hpos = pos + rel;
        // content-disposition: inline 宣言か
        let hdr_end = lower[hpos..]
            .find("\n\n")
            .map(|e| hpos + e)
            .unwrap_or(lower.len());
        let hdr = &lower[hpos..hdr_end.min(hpos + 500)];
        if hdr.contains("inline") {
            // 同じ宣言ブロック内の filename= を拾い危険拡張子判定
            if let Some(frel) = hdr.find("filename=") {
                let fval = crate::magic_bytes::is_dangerous_windows_attachment(
                    &hdr[frel + 9..]
                        .trim_start_matches(|c| c == '"' || c == '\'')
                        .split(|c: char| c == ';' || c == '"' || c.is_whitespace())
                        .next()
                        .unwrap_or(""),
                );
                if fval {
                    return true;
                }
            }
        }
        pos = hpos + 21;
    }
    false
}

