/// レンダリングパイプラインで発生するエラー。
#[derive(Debug, Error)]
pub enum RenderError {
    /// MIME パース失敗。
    #[error("parse error: {0}")]
    Parse(String),
    /// DLP ポリシーによりブロックされた。
    #[error("DLP blocked by policy: {0}")]
    DlpBlocked(String),
    /// HTML サニタイズ失敗。
    #[error("sanitizer error: {0}")]
    Sanitize(String),
}

